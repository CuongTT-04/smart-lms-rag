import { expect, it, vi } from 'vitest'
import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import SessionWorkspace from './SessionWorkspace'
import { updateClassroomSession } from '../services/course.service'
vi.mock('../services/course.service', async (original) => ({ ...await original(), updateClassroomSession: vi.fn(async (_, __, ___, values) => ({ id: 's1', ...values })) }))
vi.mock('./documents/CourseDocuments', () => ({ default: () => <div>Học liệu buổi học</div> }))
vi.mock('./videos/SessionVideos', () => ({ default: ({ uploading, onUploadingChange }) => <div>Trình phát video buổi học{uploading && <div role="dialog" aria-label="Tải video"><button onClick={() => onUploadingChange(false)}>Hủy tải video</button></div>}</div> }))
vi.mock('../services/video.service', () => ({ videoPath: () => '/videos/', listSessionVideos: vi.fn(async () => []) }))
it('requires a selected document before starting document-scoped AI chat', async () => {
  render(<SessionWorkspace course={{id:'c1'}} room={{id:'r1'}} session={{id:'w4-chat',title:'Buổi 1'}} />)
  await userEvent.click(screen.getByRole('button',{name:'Trợ lý Ayo'}))
  expect(screen.queryByRole('textbox',{name:'Câu hỏi cho ayo'})).not.toBeInTheDocument()
  expect(screen.getByText('Chọn một học liệu để bắt đầu trò chuyện và xem lịch sử.')).toBeVisible()
  expect(screen.queryByText('ayo chưa được kết nối.')).not.toBeInTheDocument()
})
it('highlights only the material in the active section and restores selection on returning', async () => {
  render(<SessionWorkspace course={{id:'c1'}} room={{id:'r1'}} session={{id:'exclusive-selection',title:'Buổi 1'}} />)
  await userEvent.click(screen.getByRole('button', {name:'Thêm học liệu'}))
  const material = screen.getByRole('button', {name:'Học liệu chưa đặt tên'})
  expect(material).toHaveAttribute('aria-current','page')
  await userEvent.click(screen.getByRole('button', {name:'Video',exact:true}))
  expect(material).not.toHaveClass('active')
  expect(material).not.toHaveAttribute('aria-current')
  await userEvent.click(material)
  expect(material).toHaveClass('active')
  expect(material).toHaveAttribute('aria-current','page')
})
it('opens and reopens video upload from the teacher sidebar', async () => {
  render(<SessionWorkspace course={{id:'c1'}} room={{id:'r1'}} session={{id:'sidebar-upload',title:'Buổi 1'}} />)
  await userEvent.click(screen.getByRole('button', {name:'Video',exact:true}))
  await userEvent.click(screen.getByRole('button', {name:'Thêm video'}))
  expect(screen.getByRole('dialog', {name:'Tải video'})).toBeVisible()
  await userEvent.click(screen.getByRole('button', {name:'Hủy tải video'}))
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  await userEvent.click(screen.getByRole('button', {name:'Thêm video'}))
  expect(screen.getByRole('dialog', {name:'Tải video'})).toBeVisible()
})
it.each([true, false])('lets the video section collapse without leaving its content (teacher=%s)', async (canManage) => {
  render(<SessionWorkspace canManage={canManage} course={{id:'c1'}} room={{id:'r1'}} session={{id:`video-collapse-${canManage}`,title:'Buổi video'}} />)
  const toggle = screen.getByRole('button', {name:'Video',exact:true})
  await userEvent.click(toggle)
  expect(toggle).toHaveAttribute('aria-expanded','true')
  expect(screen.getByText('Chưa có video')).toBeVisible()
  expect(screen.getByText('Trình phát video buổi học')).toBeVisible()
  await userEvent.click(toggle)
  expect(toggle).toHaveAttribute('aria-expanded','false')
  expect(screen.getByText('Chưa có video').closest('[aria-hidden]')).toHaveAttribute('aria-hidden','true')
  expect(screen.getByText('Chưa có video').closest('[inert]')).toBeInTheDocument()
  expect(screen.getByText('Trình phát video buổi học')).toBeVisible()
  await userEvent.click(toggle)
  expect(toggle).toHaveAttribute('aria-expanded','true')
  expect(screen.getByText('Chưa có video')).toBeVisible()
})
it('finalizes a draft session independently of the selected PDF', async () => {
  const saved = vi.fn()
  render(<SessionWorkspace course={{id:'c1'}} room={{id:'r1'}} session={{id:'s1',title:'Buổi 1',is_draft:true}} onSaved={saved} />)
  expect(screen.getByText('Bản nháp')).toBeVisible()
  await userEvent.click(screen.getByRole('button', { name: 'Tạo buổi học' }))
  expect(updateClassroomSession).toHaveBeenCalledWith('c1','r1','s1',{is_draft:false})
  expect(saved).toHaveBeenCalledWith(expect.objectContaining({is_draft:false}))
  expect(screen.queryByText('Bản nháp')).not.toBeInTheDocument()
  expect(screen.getByRole('button',{name:'Đã tạo buổi học'})).toBeDisabled()
})
it('keeps sidebar content mounted but inaccessible while collapsed and restores it on opening', async () => {
  render(<SessionWorkspace course={{id:'c1'}} room={{id:'r1'}} session={{id:'s1',title:''}} />)
  await userEvent.click(screen.getByRole('button', {name:'Thêm học liệu'}))
  const menu = screen.getByRole('button', {name:'Ẩn hiện nội dung buổi học'})
  await userEvent.click(screen.getByRole('button', {name:'Đóng thanh nội dung'}))
  expect(menu).toHaveFocus()
  expect(menu).toHaveAttribute('aria-expanded','false')
  expect(screen.queryByRole('navigation',{name:'Nội dung buổi học'})).not.toBeInTheDocument()
  expect(document.querySelector('.session-sidebar-slot')).toHaveAttribute('inert')
  expect(document.querySelector('.session-content-sidebar')).toBeInTheDocument()
  await userEvent.click(menu)
  expect(menu).toHaveAttribute('aria-expanded','true')
  expect(screen.getByRole('button',{name:'Học liệu chưa đặt tên'})).toBeVisible()
})
it('opens a green content sidebar and saves a session title', async () => {
  const back = vi.fn()
  render(<SessionWorkspace course={{id:'c1'}} room={{id:'r1'}} session={{id:'s1',title:''}} onBack={back} />)
  expect(screen.getByRole('navigation', { name: 'Nội dung buổi học' })).toBeVisible()
  await userEvent.click(screen.getByRole('button', { name: 'Đổi tên buổi học' }))
  await userEvent.type(screen.getByLabelText('Tên buổi học'), 'Ngày 1')
  await userEvent.click(screen.getByRole('button', { name: 'Lưu tên buổi học' }))
  expect(updateClassroomSession).toHaveBeenCalledWith('c1', 'r1', 's1', {title:'Ngày 1'})
  expect(await screen.findByRole('heading', {name:'Ngày 1'})).toBeVisible()
  await userEvent.click(screen.getByRole('button', { name: 'Trợ lý Ayo' }))
  expect(screen.getByRole('complementary', { name:'Trợ lý Ayo — Bạn đồng hành học tập' })).toBeVisible()
  await userEvent.click(screen.getByRole('button', { name:'Các buổi học' }))
  expect(back).toHaveBeenCalled()
})
